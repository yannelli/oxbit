import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
const catalog = JSON.parse(
  await readFile("packages/themes/src/catalog.json", "utf8"),
);
const paths = execFileSync(
  "rg",
  [
    "--files",
    "packages/ui/src",
    "packages/workbench/src",
    "packages/features",
    "apps/web/src",
    "apps/desktop/src",
  ],
  { encoding: "utf8" },
)
  .trim()
  .split("\n")
  .filter(
    (p) =>
      /\.(tsx?|css)$/.test(p) &&
      !p.includes("/themes/") &&
      !/\.test\.|\.generated\./.test(p),
  );
const variables = new Map(
  Object.entries(catalog.colors).map(([k, v]) => [v.css, "colors." + k]),
);
for (const [k, v] of Object.entries(catalog.syntax))
  for (const suffix of ["", "-background", "-weight", "-style", "-decoration"])
    variables.set(v.css + suffix, "syntax." + k);
for (const role of Object.keys(catalog.typography))
  for (const property of [
    "font-family",
    "font-size",
    "font-weight",
    "font-style",
    "line-height",
    "letter-spacing",
    "font-variant-ligatures",
    "font-variation-settings",
  ])
    variables.set(`--font-${role}-${property}`, "typography." + role);
variables.set("--font-mono", "typography.mono");
variables.set("--shadow", "effects.shadow");
paths.sort();
const rows = [],
  errors = [];
for (const path of paths) {
  const text = await readFile(path, "utf8");
  const roles = new Set(
    [...text.matchAll(/var\((--[\w-]+)/g)]
      .map((m) => variables.get(m[1]))
      .filter(Boolean),
  );
  if (roles.size)
    rows.push(
      `| \`${path}\` | ${[...roles]
        .sort()
        .map((r) => "`" + r + "`")
        .join(", ")} |`,
    );
  // Renderer adapters may compute numeric values. Owned paints must not introduce raw colors/families/sizes.
  if (
    path !== "packages/ui/src/tokens.css" &&
    /#[\da-f]{3,8}\b|rgba?\(\s*\d/i.test(text)
  )
    errors.push(path + ": raw color");
  if (
    path !== "packages/workbench/src/contributions.ts" &&
    /fontSize:\s*\d|fontFamily:\s*["'][^v][^"']*["']/.test(text)
  )
    errors.push(path + ": raw font");
  if (/font-size:\s*\d+(?:\.\d+)?px|font-family:\s*['"]/.test(text))
    errors.push(path + ": raw CSS font");
}
const doc = `# Theme surface inventory\n\nGenerated by \`pnpm themes:coverage\`. Every shared palette variable maps to a catalog entry. CSS family and size literals and raw owned colors fail the check. The adapters are verified separately with a distinct value for every catalog color.\n\n| Surface source | Catalog roles consumed |\n| --- | --- |\n${rows.join("\n")}\n\n## Renderer mappings\n\n- CodeMirror: keyword, string, number, comment, type, function, property, variable, ident, text, tag, attr, punct, operator, heading, link, strong, emphasis. Tags use all five syntax style properties. Strong and emphasis preserve Markdown semantics. Gutter, cursor, guides, occurrences, selections, search and diagnostic decorations use semantic colors.\n- xterm: foreground, background, cursor, cursorAccent, three selection properties, all 16 ANSI colors; SearchAddon receives match and active match backgrounds, borders and overview colors. Size, family, weight, line height, letter spacing and ligatures update without replacing the terminal. xterm has no font-style or variable-axis option; these properties apply to DOM/CodeMirror renderers only.\n- Workbench and native-shell roots: cssVariables plus effective UI typography. Native popovers remain descendants of the originating root and inherit its variables. Web connection overlays explicitly apply the same variables.\n- Rendered Markdown: document typography, preview background/foreground, semantic links, code, tables and quote chrome.\n- Collaboration: local awareness cursor/selection values update with the theme; remote participants' colors are peer-provided identity data.\n\n## Explicit exemptions\n\n- Brand marks, logo URLs and brand accent in tokens.css remain host identity, as required by v1's boundary. The initial body fallback uses the catalog's dark workbench background before a session mounts.\n- Row/tab/control sizes and responsive density are layout. Relative font-size ratios preserve existing hierarchy; font-style italic on preview tabs and text-decoration on missing files communicate state. Markdown strong/emphasis communicates document semantics.\n- Numeric font values inside adapters come from resolved typography or explicit settings. Native font-face declarations under public/fonts register application assets, not role selection.\n- Editor folding icons and transparent hit regions are geometry, not palette colors. Vendor CSS, external preview contents, OS dialogs, brand assets and application-emitted terminal truecolor are outside the owned surface inventory.\n`;
if (errors.length) {
  console.error(errors.join("\n"));
  process.exitCode = 1;
} else if (process.argv.includes("--check")) {
  if ((await readFile("docs/theme-coverage.md", "utf8")) !== doc) {
    console.error("Theme inventory is stale; run pnpm themes:coverage");
    process.exitCode = 1;
  }
} else await writeFile("docs/theme-coverage.md", doc);
