// Builds the iOS language server bundles, then writes the license notices for every bundled package.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { bundled } from "./build-language-servers.mjs";

const root = fileURLToPath(new URL("../../", import.meta.url));
const target = join(root, "apps/web/public/licenses/ios-language-servers.txt");
const schemaIndex = JSON.parse(readFileSync(join(root, "packages/features/language/schemas/index.json"), "utf8"));
const packages = new Map();
for (const [kind, directories] of Object.entries(bundled))
  for (const directory of directories) {
    const manifest = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
    const key = `${manifest.name} ${manifest.version}`;
    const license = typeof manifest.license === "string" ? manifest.license : manifest.license?.type ?? "SEE LICENSE FILE";
    if (/GPL/.test(license) && !/LGPL/.test(license)) throw new Error(`${key} is ${license}; GPL code cannot ship in the app`);
    const entry = packages.get(key) ?? { name: manifest.name, version: manifest.version, license, kinds: new Set(), directory };
    entry.kinds.add(kind);
    packages.set(key, entry);
  }
/** Extra notices for code embedded in a package: Ruff's crate notices and the typeshed license inside the pyright worker. */
const embedded = {
  "@astral-sh/ruff-wasm-web": () => readFileSync(join(root, "apps/runtime/src/managed/licenses/ruff.txt"), "utf8").trim(),
  "browser-basedpyright": (directory) => {
    const worker = readFileSync(join(directory, "dist/pyright.worker.js"), "utf8");
    const start = worker.indexOf("\"/typeshed-fallback/LICENSE\":'") + "\"/typeshed-fallback/LICENSE\":'".length;
    let end = start;
    while (worker[end] !== "'" || worker[end - 1] === "\\") end++;
    return "typeshed (embedded as /typeshed-fallback/LICENSE)\n\n" + worker.slice(start, end).replace(/\\(.)/g, (_, character) => character === "n" ? "\n" : character).trim();
  },
};
const licenseText = (directory) => {
  const file = readdirSync(directory).find(name => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(name));
  return file ? readFileSync(join(directory, file), "utf8").trim() : undefined;
};
const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const lines = [
  "Third-party notices for the iOS language servers",
  "",
  "These npm packages are bundled into the Oxbit iOS app's on-device language servers",
  "(apps/ios/src-tauri/gen/apple/assets/language-servers). Each package keeps its own license.",
  "The package's published license file follows the list. Generated by scripts/ios/language-server-notices.mjs.",
  "",
  "Packages",
  "--------",
  ...sorted.map(item => `${item.name} ${item.version}: ${item.license} (${[...item.kinds].join(", ")})`),
  "",
  "Bundled data",
  "------------",
  `JSON schemas retrieved ${schemaIndex.retrieved}: ${schemaIndex.license}`,
  ...Object.entries(schemaIndex.schemas).map(([url, item]) => `${item.file}: ${url}`),
  "",
  "Bundled third-party data inside packages",
  "----------------------------------------",
  "browser-basedpyright: Pyright (MIT) and typeshed (Apache-2.0); both notices follow its entry below.",
  "@astral-sh/ruff-wasm-web: Ruff's license and third-party crate notices follow its entry below.",
];
for (const item of sorted) {
  const text = licenseText(item.directory);
  lines.push("", "=".repeat(78), `${item.name} ${item.version}`, "=".repeat(78), text ?? `No license file is published; package.json declares ${item.license}.`);
  const extra = embedded[item.name]?.(item.directory);
  if (extra) lines.push("", extra);
}
const output = lines.join("\n").replace(/\r\n?/g, "\n") + "\n";
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== output) throw new Error("Run node scripts/ios/language-server-notices.mjs to update ios-language-servers.txt");
} else writeFileSync(target, output);
console.log(`${packages.size} packages`);
