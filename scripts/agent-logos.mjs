// Vendors the ACP Registry agent icons (16px, currentColor SVG) into the agent panel.
// Usage: node scripts/agent-logos.mjs [registry commit]
import { writeFile } from "node:fs/promises";

const commit = process.argv[2] ?? "06c62b5944eb863e5de30580b25334f9c4fa3962";
const raw = (file) => `https://raw.githubusercontent.com/agentclientprotocol/registry/${commit}/${file}`;
const tree = await fetch(`https://api.github.com/repos/agentclientprotocol/registry/git/trees/${commit}?recursive=1`).then((response) => {
  if (!response.ok) throw new Error(`Registry tree: HTTP ${response.status}`);
  return response.json();
});
const ids = tree.tree.map((entry) => entry.path.match(/^([a-z0-9-]+)\/icon\.svg$/)?.[1]).filter(Boolean).sort();
const unsafe = /<script|<foreignObject|<image|\bhref\s*=|\son[a-z]+\s*=|url\(/i;
const logos = {};
for (const id of ids) {
  const response = await fetch(raw(`${id}/icon.svg`));
  if (!response.ok) throw new Error(`${id}: HTTP ${response.status}`);
  const svg = (await response.text()).replace(/<\?xml[^>]*>/, "").replace(/<!--[\s\S]*?-->/g, "").replace(/>\s+</g, "><").replace(/\s+/g, " ").trim();
  if (!svg.startsWith("<svg") || unsafe.test(svg)) throw new Error(`${id}: icon has unexpected content`);
  logos[id] = svg;
}
const license = await fetch(raw("LICENSE")).then((response) => response.text());
await writeFile("packages/features/agent-acp/LICENSE.acp-registry.txt", license);
await writeFile(
  "packages/features/agent-acp/src/agent-logos.ts",
  `// Generated by scripts/agent-logos.mjs from agentclientprotocol/registry ${commit}.
// The icons are Apache-2.0; see ../LICENSE.acp-registry.txt.
export const AGENT_LOGOS: Readonly<Record<string, string>> = ${JSON.stringify(logos, null, 2)};
`,
);
console.log(`Vendored ${ids.length} agent icons from ${commit}`);
