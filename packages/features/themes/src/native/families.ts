export type Color = "blue" | "red" | "orange" | "purple" | "green" | "yellow" | "teal" | "pink" | "gray";

/** Solid tiles mark source languages; tinted tiles mark manifests, tools and config; glyphs mark formats. */
export type FileFamily =
  | { kind: "solid"; color: Color; label: string; ink?: Color }
  | { kind: "tint"; color: Color; label: string }
  | { kind: "glyph"; glyph: string; color: Color }
  | { kind: "test"; base: string };

export interface FolderFamily { color: Color; badge?: string }

const solid = (color: Color, label: string, ink?: Color): FileFamily => ({ kind: "solid", color, label, ink });
const tint = (color: Color, label: string): FileFamily => ({ kind: "tint", color, label });
const glyph = (name: string, color: Color): FileFamily => ({ kind: "glyph", glyph: name, color });
const test = (base: string): FileFamily => ({ kind: "test", base });

